HEADER = '# Generated by experiment.py tasks sync-pier; edit task.json/source inputs.\n'


def json_bytes(value):
    return (json.dumps(value, ensure_ascii=False, indent=2, allow_nan=False) + '\n').encode()


def toml_value(value):
    # Our metadata uses strings and lists of strings; JSON's subset is valid TOML.
    if not isinstance(value, str) and not (
        isinstance(value, list) and all(isinstance(item, str) for item in value)
    ):
        raise ValueError('Pier metadata must contain strings or lists of strings')
    return json.dumps(value, ensure_ascii=True)


def collect_command(base, workspace='/app', output='/logs/artifacts/model.patch'):
    import shlex
    q = shlex.quote
    return (f'cd {q(workspace)} && mkdir -p {q(str(Path(output).parent))} && '
            f'git config --global --add safe.directory {q(workspace)} && '
            f'git diff --binary {q(base)} HEAD > {q(output)}')


def derived_files(directory, task):
    if task['pier']['schema_version'] != 1:
        raise ValueError('Unsupported Pier derived-input schema')
    if task['tests'] != 'tests':
        raise ValueError('Pier requires the tests directory to be named tests')
    candidate = safe_child(directory, task['candidate_patch']).read_bytes()
    positive = safe_child(directory, task['positive_control']).read_bytes()
    manifest = safe_child(directory, task['candidate_files']).read_bytes()
    state = {
        'base_commit': task['base_commit'],
        'expected_initial_tree_sha256': task['expected_initial_tree_sha256'],
        'candidate_patch_sha256': hashlib.sha256(candidate).hexdigest(),
    }
    oracle_state = {**state, 'positive_control_sha256': hashlib.sha256(positive).hexdigest()}
    helper = Path(__file__).with_name('candidate_state.py').read_bytes()
    metadata = {**task['pier'].get('metadata', {}), 'task_id': task['id'],
                'base_commit_hash': task['base_commit'], 'evaluation_type': 'candidate-repair',
                'initial_state': 'uncommitted-c0'}
    tags = list(dict.fromkeys(['candidate-repair', 'c0', metadata.get('language', 'code')]))
    description = 'Continue repairing the loaded C0 candidate: ' + task['description']
    command = collect_command(task['base_commit'])
    toml = HEADER + f'''schema_version = "1.3"
artifacts = ["/logs/artifacts/model.patch"]

[task]
name = "fixed-patch/{task['id']}"
description = {toml_value(description)}
authors = []
keywords = {toml_value(tags)}

[metadata]
'''
    toml += ''.join(f'{toml_value(key)} = {toml_value(value)}\n' for key, value in sorted(metadata.items()))
    toml += f'''
[verifier]
network_mode = "no-network"
environment_mode = "separate"
timeout_sec = 1800.0

[verifier.env]

[verifier.environment]
build_timeout_sec = 1800.0
cpus = 2
memory_mb = 8192
storage_mb = 20480
gpus = 0
os = "linux"
workdir = "/app"

[[verifier.collect]]
command = {toml_value(command)}
timeout_sec = 300.0

[agent]
network_mode = "no-network"
timeout_sec = 10800.0

[environment]
build_timeout_sec = 1800.0
os = "linux"
workdir = "/app"
cpus = 2
memory_mb = 8192
storage_mb = 20480
gpus = 0
mcp_servers = []

[environment.env]

[solution.env]
'''
    dockerfile = HEADER + f'''FROM {task['image']}
WORKDIR /app
COPY candidate.patch candidate-files.json state.json candidate_state.py /opt/fixed-patch/
RUN python3 /opt/fixed-patch/candidate_state.py init /app /opt/fixed-patch
CMD ["/bin/bash"]
'''
    verifier = HEADER + f'''FROM {task['image']}
WORKDIR /app
ENV PATH="/root/go/bin:${{PATH}}"
COPY test.sh test.patch grader.py config.json /tests/
RUN chmod +x /tests/test.sh
CMD ["/bin/bash"]
'''
    return {
        'instruction.md': safe_child(directory, task['prompt']).read_bytes(),
        'task.toml': toml.encode(),
        'pre_artifacts.sh': ('#!/bin/bash\n' + HEADER + 'set -euo pipefail\n' + command + '\n').encode(),
        'environment/Dockerfile': dockerfile.encode(),
        'environment/.dockerignore': b'*\n!Dockerfile\n!candidate.patch\n!candidate-files.json\n!state.json\n!candidate_state.py\n',
        'environment/candidate.patch': candidate,
        'environment/candidate-files.json': manifest,
        'environment/state.json': json_bytes(state),
        'environment/candidate_state.py': helper,
        'tests/Dockerfile': verifier.encode(),
        'solution/solve.sh': ('#!/bin/bash\n' + HEADER + 'set -euo pipefail\n'
                              'python3 /solution/candidate_state.py oracle /app /solution\n').encode(),
        'solution/state.json': json_bytes(oracle_state),
        'solution/candidate-files.json': manifest,
        'solution/historical-final.patch': positive,
        'solution/candidate_state.py': helper,
    }


def validate_derived(directory, task):
    expected = derived_files(directory, task)
    for relative, content in expected.items():
        path = safe_child(directory, relative)
        if not path.is_file() or path.read_bytes() != content:
            raise ValueError('Pier derived input differs; run tasks sync-pier then seal: '
                             + task['id'] + '/' + relative)
    # These two contexts are self-contained allowlists, never entire task copies.
    for context in ('environment', 'solution'):
        actual = {p.relative_to(directory).as_posix()
                  for p in (directory / context).rglob('*') if p.is_file()}
        allowed = {p for p in expected if p.startswith(context + '/')}
        if actual != allowed:
            raise ValueError('Unexpected files in Pier ' + context + ': ' + task['id'])


def sync(directory):
    from .catalog import validate_task
    directory = Path(directory).resolve()
    task = validate_task(directory, hashes=False, pier=False)
    task.setdefault('pier', {'schema_version': 1, 'metadata': {}})
    outputs = derived_files(directory, task)
    sources = {task[key] for key in ('prompt', 'candidate_patch', 'candidate_files', 'positive_control')}
    if sources.intersection(outputs):
        raise ValueError('Pier generated paths must not overwrite authoritative source inputs')
    for relative in outputs:
        safe_child(directory, relative)
    for relative, content in outputs.items():
        path = directory / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(content)
        path.chmod(0o755 if path.suffix == '.sh' else 0o644)
    write_json(directory / 'task.json', task)
    validate_derived(directory, task)
    return len(outputs)
